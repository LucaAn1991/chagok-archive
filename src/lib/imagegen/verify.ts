import { BASE_SYSTEM, STR, STR_ARRAY, callJson, obj } from "../ai/client";

/**
 * 만들어진 카드가 **제대로 나왔는지 보고 판정한다** (09-02).
 *
 * **왜 필요한가** — 6장을 만들어보니 그중 1~2장이 조용히 어긋났다. 표지에는
 * 원본 시안의 「Brand Name」이 그대로 남았고, 다른 장은 「Brand Marketing」이
 * 안 바뀐 채 나왔다. **같은 프롬프트인데 장마다 결과가 다르다.** 이게 이 방식의
 * 유일하게 남은 약점이고, 사용자에게 그런 카드가 가면 안 된다.
 *
 * 글자만으로는 판정할 수 없다 — 그림을 봐야 안다. 그래서 클로드에게 **결과 그림을
 * 보여주고** 물어본다.
 *
 * **사용자가 올린 사진도 함께 검사한다.** 사진은 「내 가게·내 물건」이라는 증거라,
 * 모델이 비슷한 다른 사진으로 바꿔 그리면 제품의 전제가 무너진다. 실측에서는
 * 원본이 잘 유지됐지만 **매번 그러리라는 보장이 없어서** 검사 항목에 넣는다.
 *
 * **판정을 후하게 하지 않도록 «무엇이 실패인지»를 못박는다.** 「괜찮아 보인다」는
 * 판정은 쓸모가 없다.
 */

const VERDICT_SCHEMA = obj(
  {
    ok: { type: "boolean" },
    problems: STR_ARRAY,
    note: STR,
  },
  ["ok", "problems", "note"],
);

export type Verdict = {
  ok: boolean;
  /** 무엇이 잘못됐는지 — 다시 만들 때 프롬프트에 얹는다 */
  problems: string[];
  note: string;
};

const SYSTEM = [
  BASE_SYSTEM,
  "",
  "지금은 기획을 돕는 게 아니라 **검사원**이다. 만들어진 카드뉴스 한 장이 요청대로 나왔는지 판정한다.",
  "너그럽게 보지 마라. 이 판정을 통과하면 사용자에게 그대로 나간다.",
].join("\n");

export type VerifyInput = {
  /** 검사할 결과 카드 */
  png: Buffer;
  /** 이 장에 들어가야 하는 문구들 — 순서대로 */
  expected: string[];
  /**
   * 사용자가 올린 원본 사진들 (09-02). 넘기면 «그 사진이 그대로 들어갔는지»까지 본다.
   * 안 넘기면 글자만 검사한다 — 사진을 쓰지 않는 장에서 헛물을 켜지 않게.
   */
  sourcePhotos?: Buffer[];
};

/**
 * 카드 한 장을 검사한다.
 *
 * **실패로 볼 것을 구체적으로 나열한다.** 「자연스러운가」 같은 취향 판단은 묻지
 * 않는다 — 그건 사람이 정할 일이고, 여기서 물으면 멀쩡한 카드도 떨어뜨린다.
 */
export async function verifyCard(input: VerifyInput): Promise<Verdict> {
  const photos = input.sourcePhotos ?? [];

  /*
    그림 순서를 글로 못박는다. 「첫 번째가 결과, 그다음이 원본 사진」이라고
    말해주지 않으면 모델이 무엇과 무엇을 비교하는지 모른다.
  */
  const order =
    photos.length > 0
      ? [
          `그림은 ${photos.length + 1}장이다.`,
          "**첫 번째** 그림이 검사할 결과 카드다.",
          `**두 번째부터**는 사용자가 올린 원본 사진 ${photos.length}장이다.`,
        ].join(" ")
      : "위 그림은 검사할 결과 카드다.";

  const checks = [
    "① 아래 문구들이 그림 안에 **실제로** 보이는가. 일부만 들어갔거나 빠진 것이 있는가.",
    "② 원본 템플릿의 **자리표시 문구가 남아 있는가.** 예: Brand, Brand Name, Brand Marketing,",
    "   Brand Point, Notice, 「~를 입력해주세요」, 「샘플이미지입니다」, 「소제목을 적어주세요」,",
    "   Lorem ipsum, 뜻 없이 반복되는 영문.",
    "③ 한글이 **깨졌는가.** 없는 글자, 자모가 어긋난 글자, 뭉개져 못 읽는 글자가 있는가.",
  ];

  if (photos.length > 0) {
    checks.push(
      "④ **사용자가 올린 사진이 그대로 들어갔는가.** 결과 카드 안의 사진과 원본 사진을 나란히 비교해라.",
      "   잘리거나 크기가 달라진 것은 **괜찮다** — 틀 모양에 맞추느라 자르는 것은 정상이다.",
      "   문제인 것은 «다른 사진으로 바뀐 것»이다: 물건의 모양·색·개수가 다르거나, 배경이 딴판이거나,",
      "   원본에 없던 것이 생겼거나, 사람의 얼굴·옷·자세가 달라졌으면 실패다.",
      "   원본 사진이 아예 안 쓰이고 관계없는 사진이 들어갔으면 당연히 실패다.",
    );
  }

  const user = [
    order,
    "이 카드는 정해진 디자인 템플릿의 글자만 바꿔 만든 것이다.",
    "",
    "**들어가야 하는 문구** (순서대로):",
    ...input.expected.map((t, i) => `${i + 1}) ${t}`),
    "",
    "다음을 각각 확인하고 판정해라.",
    ...checks,
    "",
    "하나라도 걸리면 `ok`는 false다.",
    "`problems`에는 걸린 것을 **고칠 수 있게** 적어라 — 「3번 문구가 빠졌다」가 아니라",
    "「제목 자리에 Brand Name이 그대로 남아 있다. 「퇴근하고 30분」으로 바뀌어야 한다」처럼.",
    "문제가 없으면 `problems`는 빈 배열이다.",
    "`note`는 한 줄 요약.",
  ].join("\n");

  return callJson<Verdict>({
    system: SYSTEM,
    user,
    imagesBase64: [input.png, ...photos].map((b) => b.toString("base64")),
    schema: VERDICT_SCHEMA,
    // 결과물의 합격 여부를 가르는 판단이라 아끼지 않는다
    effort: "medium",
  });
}
